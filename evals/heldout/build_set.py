"""Assemble the held-out set from the two agents' raw outputs (plan.md).

  prepare   check raw/writer.jsonl against sections.tsv, then write
            raw/adjudicator_input.jsonl (questions only, in a seeded shuffled
            order, under ids that don't reveal their section) and
            raw/qid_map.tsv
  assemble  join the writer's and adjudicator's outputs into questions.yaml

Nothing here edits a question or a label; it only checks shape and joins.

Run: ../../packages/server-py/.venv/bin/python build_set.py prepare|assemble
"""

from __future__ import annotations

import json
import os
import random
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "raw")
SHUFFLE_SEED = 20261008
DOC_IDS = {
    "kleidiai-readme", "llamacpp-build", "kleidiai-matmul-pack", "kleidiai-microkernel-names",
    "kleidiai-matmul-qsi4cx", "learnarm-llamacpp-sme2-integration", "mlexamples-llamacpp-int4-patch",
}


def read_jsonl(name: str) -> list[dict]:
    with open(os.path.join(RAW, name)) as fh:
        return [json.loads(line) for line in fh if line.strip()]


def sections() -> list[dict]:
    with open(os.path.join(HERE, "sections.tsv")) as fh:
        rows = [line.rstrip("\n").split("\t") for line in fh][1:]
    return [{"section_id": r[0], "doc_id": r[1]} for r in rows]


def writer_rows() -> list[dict]:
    rows, secs = read_jsonl("writer.jsonl"), sections()
    assert [r["section_id"] for r in rows] == [s["section_id"] for s in secs], "writer output must cover every section, in order"
    for r in rows:
        assert (r["question"] is None) != (r["skip_reason"] is None), f"{r['section_id']}: exactly one of question / skip_reason"
    for r, s in zip(rows, secs):
        r["doc_id"] = s["doc_id"]
    return rows


def prepare() -> None:
    rows = writer_rows()
    asked = [r for r in rows if r["question"] is not None]
    order = list(range(len(asked)))
    random.Random(SHUFFLE_SEED).shuffle(order)
    with open(os.path.join(RAW, "adjudicator_input.jsonl"), "w") as fh, \
            open(os.path.join(RAW, "qid_map.tsv"), "w") as mp:
        mp.write("qid\tsection_id\n")
        for pos, i in enumerate(order, 1):
            qid = f"q{pos:03d}"
            fh.write(json.dumps({"qid": qid, "question": asked[i]["question"]}) + "\n")
            mp.write(f"{qid}\t{asked[i]['section_id']}\n")
    print(f"{len(asked)} questions; {len(rows) - len(asked)} sections skipped by the writer")


def assemble() -> None:
    rows = {r["section_id"]: r for r in writer_rows()}
    with open(os.path.join(RAW, "qid_map.tsv")) as fh:
        qid_section = dict(line.rstrip("\n").split("\t") for line in list(fh)[1:])
    labels = read_jsonl("adjudicator.jsonl")
    assert [lab["qid"] for lab in read_jsonl("adjudicator_input.jsonl")] == [lab["qid"] for lab in labels], \
        "adjudicator output must cover every question, in order"
    out, unanswerable = [], []
    for lab in labels:
        unknown = set(lab["answering_doc_ids"]) - DOC_IDS
        assert not unknown, f"{lab['qid']}: unknown doc ids {unknown}"
        r = rows[qid_section[lab["qid"]]]
        if not lab["answering_doc_ids"]:
            unanswerable.append(r["section_id"])
            continue
        others = sorted(set(lab["answering_doc_ids"]) - {r["doc_id"]})
        out.append({
            "id": "ho-" + r["section_id"].replace("#", "-"),
            "question": r["question"],
            "expected_doc_ids": [r["doc_id"]] + others,
            "source_section": r["section_id"],
            "adjudicator_listed_source": r["doc_id"] in lab["answering_doc_ids"],
            "expected_tool": None,
            "expected_tool_args": None,
            "notes": lab.get("note", ""),
        })
    out.sort(key=lambda q: q["source_section"])
    header = ("# Held-out QA set (evals/heldout/plan.md). Never used to choose or tune\n"
              "# anything; if it ever is, it becomes a development set. Generated by\n"
              "# build_set.py from raw/: do not edit by hand.\n")
    with open(os.path.join(HERE, "questions.yaml"), "w") as fh:
        fh.write(header)
        yaml.safe_dump({"version": 1, "excluded_unanswerable": unanswerable, "questions": out}, fh,
                       sort_keys=False, allow_unicode=True, width=100)
    print(f"{len(out)} questions; {len(unanswerable)} excluded as unanswerable by every doc")


if __name__ == "__main__":
    {"prepare": prepare, "assemble": assemble}[sys.argv[1]]()
